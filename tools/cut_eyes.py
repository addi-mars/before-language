"""Cut the reflection's irises into their own sprites so they can move.

For the reflection (and its 40% glaze copy):
  - iris sprite per eye: the painted iris + pupil, soft-edged, transparent elsewhere
  - an "eyeless" copy of the layer: the iris area refilled with eye-white,
    spread inward from the visible whites so the painted shading carries on
The site draws the eyeless layer, then each iris clipped to the eye opening
(an ellipse sitting just inside the lids), shifted toward the viewer.
Run: python3 web/tools/cut_eyes.py web/assets
"""
import json, sys
import numpy as np
from PIL import Image

ASSETS = sys.argv[1]
man = json.loads(open(f"{ASSETS}/manifest.js").read().split("=", 1)[1].rstrip().rstrip(";"))["assets"]
# in the reflection layer's own pixels (its manifest box starts at 641,127)
EYES = {
    # "open" is the visible white between the lash line and the lower lid, so
    # the lashes are never touched and the iris tucks under the upper lid
    "L": {"iris": (323.0, 199.0), "r": 9.5, "open": (324.0, 200.2), "rx": 18.0, "ry": 3.7},
    "R": {"iris": (403.5, 221.8), "r": 8.0, "open": (406.0, 222.8), "rx": 15.0, "ry": 4.8},
}

def layer(key):
    a = man[key]
    im = Image.open(f"{ASSETS}/png/{key}.png").convert("RGBA").crop((a["x"], a["y"], a["x"] + a["w"], a["y"] + a["h"]))
    return np.asarray(im).astype(np.float64), a

def process(key, out_base):
    px, a = layer(key)
    H, W = px.shape[:2]
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float64)
    result = px.copy()
    sprites = {}
    for name, e in EYES.items():
        cx, cy = e["iris"]
        d = np.hypot(xx - cx, yy - cy)
        iris_soft = np.clip((e["r"] + 2.5 - d) / 1.5, 0, 1)            # covers the hole fully, soft edge beyond it
        ox, oy = e["open"]
        inside_open = ((xx - ox) / (e["rx"] + 1)) ** 2 + ((yy - oy) / (e["ry"] + 0.6)) ** 2 < 1
        hole = (d < e["r"] + 1.5) & inside_open
        # sprite: iris pixels with soft alpha, cropped to a small box
        x0, y0 = int(cx - e["r"] - 5), int(cy - e["r"] - 5)
        x1, y1 = int(cx + e["r"] + 6), int(cy + e["r"] + 6)
        spr = px[y0:y1, x0:x1].copy()
        spr[..., 3] = spr[..., 3] * iris_soft[y0:y1, x0:x1]
        sprites[name] = (spr, x0, y0)
        # eye-white fill: diffuse from bright (sclera) pixels around the hole
        lum = px[..., :3].mean(-1)
        wider = ((xx - ox) / (e["rx"] + 3)) ** 2 + ((yy - oy) / (e["ry"] + 2)) ** 2 < 1
        known = wider & ~hole & (lum > 150)
        fill = result[..., :3].copy()
        mean_sclera = px[known][:, :3].mean(0) if known.any() else np.array([225, 215, 210.0])
        fill[hole] = mean_sclera
        fixed = known | ~wider
        for _ in range(400):                                          # Jacobi diffusion
            avg = (np.roll(fill, 1, 0) + np.roll(fill, -1, 0) + np.roll(fill, 1, 1) + np.roll(fill, -1, 1)) / 4
            upd = hole
            fill[upd] = avg[upd]
        # only the hole changes; keep a hint of the lid's shadow along the top
        shade = np.clip(1 - (yy - (oy - e["ry"])) / (e["ry"] * 1.2), 0, 1) * 0.18
        newc = fill * (1 - shade[..., None])
        result[hole, :3] = newc[hole]
        result[hole, 3] = px[hole, 3]
    Image.fromarray(np.clip(result, 0, 255).astype("uint8"), "RGBA").save(f"{ASSETS}/eyes/{out_base}-eyeless.webp", lossless=True)
    meta = {}
    for name, (spr, x0, y0) in sprites.items():
        Image.fromarray(np.clip(spr, 0, 255).astype("uint8"), "RGBA").save(f"{ASSETS}/eyes/{out_base}-iris-{name}.png")
        meta[name] = {"x": x0, "y": y0, "w": spr.shape[1], "h": spr.shape[0]}
    return meta

meta = {"eyes": EYES,
        "reflection": process("scene-a/reflection", "reflection"),
        "glaze": process("scene-a/reflection-glaze", "glaze")}
with open(f"{ASSETS}/eyes/eyes.js", "w") as f:
    f.write("// Generated by tools/cut_eyes.py\nwindow.PERCEPTION_EYES = " + json.dumps(meta, indent=1) + ";\n")
print("ok")
